# 心情关键词 → 状态（按顺序匹配，越靠前越优先）
MOOD_RULES: list[tuple[tuple[str, ...], str]] = [
    (("困", "睡", "熬夜", "失眠"), "睡觉中"),
    (("疲惫", "累", "乏", "没劲", "虚"), "被掏空"),
    (("emo", "难过", "委屈", "低落", "丧", "烦"), "emo中"),
    (("生气", "火大", "炸毛", "气"), "我太难了"),
    (("开心", "高兴", "好耶", "兴奋", "乐"), "元气满满"),
    (("害羞", "脸红", "心虚"), "我没事"),
    (("恍惚", "发呆", "放空"), "想静静"),
    (("忙", "干活", "工作", "写代码", "加班"), "搬砖中"),
    (("闲", "躺着", "摸鱼", "懒"), "摸鱼中"),
    (("饿", "馋", "饭"), "摸鱼中"),
    (("无聊", "没事干"), "无聊中"),
    (("平稳", "平静", "悠", "放松"), "悠哉哉"),
]


def pick_status(mood_text: str, hour: int | None = None) -> str:
    """按心情挑一个状态名；挑不到就按时间给个兜底。"""

    text = str(mood_text or "").lower()
    for keywords, status in MOOD_RULES:
        if any(k in text for k in keywords):
            return status
    if hour is not None:
        if 0 <= hour < 6:
            return "睡觉中"
        if 6 <= hour < 9:
            return "元气满满"
        if 9 <= hour < 12:
            return "搬砖中"
        if 12 <= hour < 14:
            return "摸鱼中"
        if 14 <= hour < 18:
            return "搬砖中"
        if 18 <= hour < 22:
            return "悠哉哉"
        return "熬夜中"
    return "在线"
